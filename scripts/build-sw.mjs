// After `next build` (static export to out/), write out/sw.js that precaches every
// file so the app opens and works with no network (app-plan.md §7).
import { readdirSync, statSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { createHash } from "node:crypto";

const OUT = new URL("../out/", import.meta.url).pathname;
const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else files.push("/" + relative(OUT, p).split("\\").join("/"));
  }
})(OUT);

const precache = files.filter((f) => f !== "/sw.js" && !f.endsWith(".map") && f !== "/404.html").sort();
const hash = createHash("sha256");
for (const f of precache) hash.update(f).update(readFileSync(join(OUT, f)));
const version = hash.digest("hex").slice(0, 12);

const sw = `// Generated by scripts/build-sw.mjs — do not edit.
const CACHE = "clusterlog-${version}";
const PRECACHE = ${JSON.stringify(["/", ...precache])};

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("clusterlog-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

// Cache first: the app must open instantly mid-attack, even offline.
self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET" || new URL(req.url).origin !== self.location.origin) return;
  e.respondWith(
    caches.match(req, { ignoreSearch: req.mode === "navigate" }).then(
      (hit) =>
        hit ||
        fetch(req).catch(() => (req.mode === "navigate" ? caches.match("/") : Response.error())),
    ),
  );
});
`;
writeFileSync(join(OUT, "sw.js"), sw);
console.log(`sw.js: ${precache.length} files precached, cache clusterlog-${version}`);
